"""Build docs/TRACEABILITY.md from requirements.yaml and the last pytest run.

    python scripts/traceability.py            regenerate the matrix, exit 1 on any error
    python scripts/traceability.py --check    exit 1 if the committed matrix is stale (CI)

The pytest plugin in tests/conftest.py writes reports/req_results.json: one entry per
test carrying a @pytest.mark.req marker, with its outcome. Run the full suite first.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass, field
from itertools import pairwise
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.yaml"
RESULTS = ROOT / "reports" / "req_results.json"
MATRIX = ROOT / "docs" / "TRACEABILITY.md"

STAGE_STATUSES = ("planned", "in_progress", "done")
VERIFIED = "verified"


@dataclass
class Requirement:
    id: str
    stage: int
    text: str
    verification: str = "test"
    evidence: str = ""
    tests: list[tuple[str, str]] = field(default_factory=list)  # (nodeid, outcome)

    @property
    def status(self) -> str:
        if self.verification == "manual":
            return VERIFIED if self.evidence.strip() else "no evidence"
        outcomes = {outcome for _, outcome in self.tests}
        if not outcomes:
            return "no test"
        if "failed" in outcomes:
            return "failing"
        if outcomes != {"passed"}:
            return "not passing"  # skipped or xfail never count as verification
        return VERIFIED


def load(
    spec: dict[str, Any], results: dict[str, dict[str, Any]]
) -> tuple[list[dict[str, Any]], list[Requirement], list[str]]:
    errors: list[str] = []
    stages: list[dict[str, Any]] = spec["stages"]
    reqs = [
        Requirement(
            id=r["id"],
            stage=r["stage"],
            text=r["text"],
            verification=r.get("verification", "test"),
            evidence=r.get("evidence", "") or "",
        )
        for r in spec["requirements"]
    ]
    by_id = {r.id: r for r in reqs}
    stage_ids = {s["id"] for s in stages}

    if len(by_id) != len(reqs):
        errors.append("duplicate requirement IDs in requirements.yaml")
    for r in reqs:
        if r.stage not in stage_ids:
            errors.append(f"{r.id}: stage {r.stage} does not exist")
        if r.verification not in ("test", "manual"):
            errors.append(f"{r.id}: unknown verification '{r.verification}'")

    for nodeid, entry in sorted(results.items()):
        for req_id in entry["reqs"]:
            if req_id not in by_id:
                errors.append(f"{nodeid}: marked with unknown requirement {req_id}")
                continue
            by_id[req_id].tests.append((nodeid, entry["outcome"]))

    for r in reqs:
        if r.verification == "manual" and r.tests:
            errors.append(f"{r.id}: manual requirement has tests; make it a test requirement")

    return stages, reqs, errors


def check_stages(stages: list[dict[str, Any]], reqs: list[Requirement]) -> list[str]:
    errors: list[str] = []
    for s in stages:
        if s["status"] not in STAGE_STATUSES:
            errors.append(f"stage {s['id']}: unknown status '{s['status']}'")

    ordered = sorted(stages, key=lambda s: s["id"])
    for earlier, later in pairwise(ordered):
        if later["status"] == "done" and earlier["status"] != "done":
            errors.append(f"stage {later['id']} is done but stage {earlier['id']} is not")

    in_progress = [s["id"] for s in stages if s["status"] == "in_progress"]
    if len(in_progress) > 1:
        errors.append(f"more than one stage in progress: {in_progress}")

    for s in stages:
        if s["status"] != "done":
            continue
        for r in reqs:
            if r.stage == s["id"] and r.status != VERIFIED:
                errors.append(f"stage {s['id']} is done but {r.id} is '{r.status}'")
    return errors


def render(stages: list[dict[str, Any]], reqs: list[Requirement]) -> str:
    lines = [
        "# Traceability",
        "",
        "> **Generated by `scripts/traceability.py`. Do not edit.** Run `make check` to refresh.",
        "",
        "## Stages",
        "",
        "| # | Stage | Status | Verified |",
        "|---|---|---|---|",
    ]
    for s in sorted(stages, key=lambda s: s["id"]):
        own = [r for r in reqs if r.stage == s["id"]]
        done = sum(r.status == VERIFIED for r in own)
        lines.append(f"| {s['id']} | {s['name']} | {s['status']} | {done}/{len(own)} |")

    for s in sorted(stages, key=lambda s: s["id"]):
        own = [r for r in reqs if r.stage == s["id"]]
        if not own:
            continue
        lines += [
            "",
            f"## Stage {s['id']} — {s['name']}",
            "",
            "| ID | Requirement | Verification | Status |",
            "|---|---|---|---|",
        ]
        for r in own:
            if r.verification == "manual":
                how = f"manual: {r.evidence}" if r.evidence else "manual"
            else:
                passed = sum(o == "passed" for _, o in r.tests)
                how = f"{passed}/{len(r.tests)} tests passing"
            lines.append(f"| {r.id} | {r.text} | {how} | {r.status} |")
        tested = [r for r in own if r.tests]
        if tested:
            lines += ["", "<details><summary>Tests</summary>", ""]
            for r in tested:
                for nodeid, outcome in sorted(r.tests):
                    lines.append(f"- `{r.id}` `{nodeid}` — {outcome}")
            lines += ["", "</details>"]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if docs/TRACEABILITY.md is stale"
    )
    args = parser.parse_args()

    spec = yaml.safe_load(REQUIREMENTS.read_text())
    if not RESULTS.exists():
        print(
            f"error: {RESULTS.relative_to(ROOT)} missing; run the full test suite first",
            file=sys.stderr,
        )
        return 1
    results = json.loads(RESULTS.read_text())

    stages, reqs, errors = load(spec, results)
    errors += check_stages(stages, reqs)
    text = render(stages, reqs)

    if args.check:
        if not MATRIX.exists() or MATRIX.read_text() != text:
            errors.append("docs/TRACEABILITY.md is stale; run `make check` and commit it")
    else:
        MATRIX.write_text(text)

    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
